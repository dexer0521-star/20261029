"""Thin REST adapters for Gemini / Claude / OpenAI (+ Mock). No vendor SDKs required.

Each provider exposes `complete_json(system, user) -> str` returning raw JSON text.
"""

from __future__ import annotations

import json
import logging
from abc import ABC, abstractmethod

import httpx

from src.config_loader import ProviderConfig, resolve_env

log = logging.getLogger(__name__)


class LLMProvider(ABC):
    def __init__(self, cfg: ProviderConfig, api_key: str | None) -> None:
        self.cfg = cfg
        self.model = cfg.model
        self.api_key = api_key
        self.name = cfg.provider

    @abstractmethod
    async def complete_json(self, client: httpx.AsyncClient, system: str, user: str, temperature: float) -> str: ...


class GeminiProvider(LLMProvider):
    async def complete_json(self, client, system, user, temperature) -> str:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent"
        body = {
            "system_instruction": {"parts": [{"text": system}]},
            "contents": [{"role": "user", "parts": [{"text": user}]}],
            "generationConfig": {
                "temperature": temperature,
                "responseMimeType": "application/json",
            },
        }
        r = await client.post(url, params={"key": self.api_key}, json=body, timeout=self.cfg.timeout_seconds)
        r.raise_for_status()
        data = r.json()
        return data["candidates"][0]["content"]["parts"][0]["text"]


class ClaudeProvider(LLMProvider):
    async def complete_json(self, client, system, user, temperature) -> str:
        headers = {"x-api-key": self.api_key or "", "anthropic-version": "2023-06-01"}
        body = {
            "model": self.model,
            "max_tokens": 4096,
            "temperature": temperature,
            "system": system,
            "messages": [{"role": "user", "content": user}, {"role": "assistant", "content": "{"}],
        }
        r = await client.post(
            "https://api.anthropic.com/v1/messages",
            headers=headers,
            json=body,
            timeout=self.cfg.timeout_seconds,
        )
        r.raise_for_status()
        text = "".join(b.get("text", "") for b in r.json()["content"] if b.get("type") == "text")
        return "{" + text


class OpenAIProvider(LLMProvider):
    async def complete_json(self, client, system, user, temperature) -> str:
        headers = {"Authorization": f"Bearer {self.api_key}"}
        body = {
            "model": self.model,
            "temperature": temperature,
            "response_format": {"type": "json_object"},
            "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}],
        }
        r = await client.post(
            "https://api.openai.com/v1/chat/completions",
            headers=headers,
            json=body,
            timeout=self.cfg.timeout_seconds,
        )
        r.raise_for_status()
        return r.json()["choices"][0]["message"]["content"]


class MockProvider(LLMProvider):
    """Deterministic offline provider used by --dry-run and tests. Echoes input URLs only."""

    def __init__(self, cfg: ProviderConfig, api_key: str | None) -> None:
        super().__init__(cfg, api_key)
        self.name, self.model = "mock", "mock"

    async def complete_json(self, client, system, user, temperature) -> str:
        payload = json.loads(user.split("INPUT:\n", 1)[1])
        items = payload["items"][: payload.get("max_items", 10)]
        return json.dumps(
            {
                "headline": f"[dry-run] {len(items)} items analysed for {payload.get('audience')}",
                "overview": "This brief was generated by the offline MockProvider. "
                "Set GEMINI_API_KEY (or ANTHROPIC_API_KEY / OPENAI_API_KEY) to get real analysis.",
                "items": [
                    {
                        "title": i["title"],
                        "url": i["url"],
                        "summary": f"{i['source']} item ranked #{i['rank']} ({i['status']}).",
                        "insight": "Mock insight: verify with the real model.",
                        "importance": max(1, 10 - idx),
                        "category": i["source"].split(":")[0],
                    }
                    for idx, i in enumerate(items)
                ],
                "rising_keywords": payload.get("rising_keywords_detected", [])[:5],
            },
            ensure_ascii=False,
        )


_PROVIDERS: dict[str, type[LLMProvider]] = {
    "gemini": GeminiProvider,
    "claude": ClaudeProvider,
    "openai": OpenAIProvider,
    "mock": MockProvider,
}


def build_provider(cfg: ProviderConfig, *, dry_run: bool = False) -> LLMProvider:
    """Instantiate a provider. Raises MissingSecret if its key is absent (unless mock/dry-run)."""
    if dry_run or cfg.provider == "mock":
        return MockProvider(cfg, None)
    key = resolve_env(cfg.api_key_env, what=f"{cfg.provider} api key")
    return _PROVIDERS[cfg.provider](cfg, key)
